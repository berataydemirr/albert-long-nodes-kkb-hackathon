"""Measure where the agent's cost actually goes - no network, no API key.

This exists to settle two claims with numbers instead of opinion:

  1. "the lakehouse tools are slow"  -> times the DuckDB work directly
  2. "the context bloats"            -> measures the argument payload the
                                        model must GENERATE for the array
                                        input path vs the Seri_Kod path

Run: python -m benchmarks.context_cost_benchmark

Output: a console table + benchmarks/context_cost_report.json
"""

import json
import statistics
import sys
import time
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):  # Windows console codepage, see agent.py
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from src.agent.context_compactor import compact_messages, estimate_tokens
from src.agent.series_resolver import DB_PATH, resolve_series
from src.agent.tools import causality_analysis, lakehouse_query, lakehouse_schema
from src.common.logging_setup import get_logger

logger = get_logger("context_cost_benchmark")

REPORT_PATH = Path(__file__).parent / "context_cost_report.json"
REPEATS = 5


def _time_it(label: str, fn, repeats: int = REPEATS) -> dict:
    """Run fn repeats times, report median so one cold cache does not
    dominate the number we then quote at people."""
    logger.info(f"_time_it: {label} starting, repeats={repeats}")
    durations = []
    for attempt in range(repeats):
        t0 = time.monotonic()
        fn()
        elapsed_ms = (time.monotonic() - t0) * 1000.0
        durations.append(elapsed_ms)
        logger.debug(f"_time_it: {label} attempt {attempt + 1}/{repeats} took {elapsed_ms:.1f}ms")
    result = {
        "label": label,
        "median_ms": round(statistics.median(durations), 2),
        "min_ms": round(min(durations), 2),
        "max_ms": round(max(durations), 2),
    }
    logger.info(f"_time_it: {label} done, median={result['median_ms']}ms")
    return result


def measure_database_cost(seri_kod: str) -> list[dict]:
    """How long the local data layer really takes, end to end."""
    logger.info("measure_database_cost: start")
    return [
        _time_it("lakehouse_schema()", lambda: lakehouse_schema()),
        _time_it("lakehouse_query() full series", lambda: lakehouse_query(
            f"SELECT Period, Deger FROM gold_fact_long WHERE Seri_Kod = '{seri_kod}' ORDER BY Period"
        )),
        _time_it("resolve_series()", lambda: resolve_series(seri_kod)),
    ]


def measure_argument_payload(x_kod: str, y_kod: str) -> dict:
    """The token cost of the two ways to call causality_analysis.

    This is the number that matters most: tool ARGUMENTS are generated by
    the model one token at a time, which is the slowest phase of inference,
    and they then stay in the history for every subsequent round.
    """
    logger.info(f"measure_argument_payload: x={x_kod}, y={y_kod}")
    x, y = resolve_series(x_kod), resolve_series(y_kod)

    array_args = json.dumps({
        "x_periods": x["periods"], "x_values": x["values"],
        "y_periods": y["periods"], "y_values": y["values"], "max_lag": 6,
    }, ensure_ascii=False)
    seri_kod_args = json.dumps({"x_seri_kod": x_kod, "y_seri_kod": y_kod, "max_lag": 6}, ensure_ascii=False)

    result = {
        "array_path_chars": len(array_args),
        "array_path_est_tokens": len(array_args) // 4,
        "seri_kod_path_chars": len(seri_kod_args),
        "seri_kod_path_est_tokens": len(seri_kod_args) // 4,
        "reduction_factor": round(len(array_args) / max(len(seri_kod_args), 1), 1),
        "series_lengths": {x_kod: x["row_count"], y_kod: y["row_count"]},
    }
    logger.info(f"measure_argument_payload: {result['array_path_chars']} -> {result['seri_kod_path_chars']} chars")
    return result


def measure_results_are_identical(x_kod: str, y_kod: str) -> dict:
    """The saving is only real if both paths produce the same statistics."""
    logger.info("measure_results_are_identical: start")
    x, y = resolve_series(x_kod), resolve_series(y_kod)

    by_arrays = causality_analysis(
        x_periods=x["periods"], x_values=x["values"],
        y_periods=y["periods"], y_values=y["values"], max_lag=3,
    )
    by_code = causality_analysis(x_seri_kod=x_kod, y_seri_kod=y_kod, max_lag=3)

    identical = (
        by_arrays["shared_periods"] == by_code["shared_periods"]
        and by_arrays["best_lag"] == by_code["best_lag"]
        and by_arrays["granger_pvalues"] == by_code["granger_pvalues"]
    )
    logger.info(f"measure_results_are_identical: identical={identical}")
    return {"identical": identical, "shared_periods": by_code["shared_periods"], "best_lag": by_code["best_lag"]}


def measure_compaction() -> dict:
    """Simulated 8-round history, the shape a long chain actually produces."""
    logger.info("measure_compaction: start")
    messages = [
        {"role": "system", "content": "system prompt"},
        {"role": "user", "content": "Konut kredisi faizi ile kredi hacmi arasinda nedensellik var mi?"},
    ]
    for i in range(8):
        payload = {
            "columns": ["Period", "Deger"],
            "rows": [{"Period": f"2021-{m % 12 + 1:02d}", "Deger": float(m)} for m in range(66)],
            "row_count": 66,
        }
        messages.append({
            "role": "assistant", "content": None,
            "tool_calls": [{"id": f"call_{i}", "function": {"name": "lakehouse_query", "arguments": "{}"}}],
        })
        messages.append({"role": "tool", "tool_call_id": f"call_{i}",
                         "content": json.dumps(payload, ensure_ascii=False)})

    before = estimate_tokens(messages)
    compacted, stats = compact_messages(messages)
    after = estimate_tokens(compacted)

    result = {
        "before_est_tokens": before,
        "after_est_tokens": after,
        "saved_est_tokens": before - after,
        "reduction_pct": round((before - after) / max(before, 1) * 100, 1),
        "messages_digested": stats["compacted_messages"],
        "message_count_unchanged": len(compacted) == len(messages),
    }
    logger.info(f"measure_compaction: {before} -> {after} est. tokens ({result['reduction_pct']}% smaller)")
    return result


def main() -> None:
    if not DB_PATH.exists():
        print(f"Gold database not found at {DB_PATH}. Run `python -m src.gold.build_gold` first.")
        raise SystemExit(1)

    import duckdb

    con = duckdb.connect(str(DB_PATH), read_only=True)
    try:
        codes = [row[0] for row in con.execute(
            "SELECT Seri_Kod FROM gold_fact_long GROUP BY Seri_Kod "
            "HAVING COUNT(*) >= 20 ORDER BY COUNT(*) DESC, Seri_Kod LIMIT 2"
        ).fetchall()]
    finally:
        con.close()

    if len(codes) < 2:
        print("Need at least two series with 20+ periods to benchmark.")
        raise SystemExit(1)

    x_kod, y_kod = codes[0], codes[1]
    logger.info(f"main: benchmarking with x={x_kod}, y={y_kod}")

    report = {
        "database_cost": measure_database_cost(x_kod),
        "argument_payload": measure_argument_payload(x_kod, y_kod),
        "results_identical": measure_results_are_identical(x_kod, y_kod),
        "compaction": measure_compaction(),
    }
    REPORT_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    print("=" * 66)
    print("CONTEXT & COST BENCHMARK (local only, no API calls)")
    print("=" * 66)
    print("\nDatabase cost (is the lakehouse the bottleneck?)")
    for entry in report["database_cost"]:
        print(f"  {entry['label']:34s} median {entry['median_ms']:8.2f} ms")

    payload = report["argument_payload"]
    print("\nTool argument payload the model must generate")
    print(f"  array path    : {payload['array_path_chars']:6d} chars (~{payload['array_path_est_tokens']} tokens)")
    print(f"  seri_kod path : {payload['seri_kod_path_chars']:6d} chars (~{payload['seri_kod_path_est_tokens']} tokens)")
    print(f"  reduction     : {payload['reduction_factor']}x smaller")
    print(f"  identical results: {report['results_identical']['identical']}")

    comp = report["compaction"]
    print("\nContext compaction over a simulated 8-round chain")
    print(f"  before: {comp['before_est_tokens']} est. tokens")
    print(f"  after : {comp['after_est_tokens']} est. tokens ({comp['reduction_pct']}% smaller)")
    print(f"  messages digested: {comp['messages_digested']}, message count unchanged: {comp['message_count_unchanged']}")
    print("-" * 66)
    print(f"Full report: {REPORT_PATH}")
    print("=" * 66)


if __name__ == "__main__":
    main()
